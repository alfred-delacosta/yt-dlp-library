import fs from "fs/promises";
import path from "path";
import { chromium } from "playwright";

const DEFAULT_SETTLE_MS = 5000;
const DEFAULT_TIMEOUT_MS = 45000;

const parsePositiveInt = (value, fallback) => {
  const n = Number.parseInt(String(value ?? ""), 10);
  return Number.isFinite(n) && n > 0 ? n : fallback;
};

const isHeaded = () => {
  const raw = String(process.env.PLAYWRIGHT_HEADED || "")
    .trim()
    .toLowerCase();
  return raw === "1" || raw === "true" || raw === "yes";
};

/**
 * Convert Playwright cookies to Netscape cookie file format for yt-dlp --cookies.
 */
export const cookiesToNetscape = (cookies) => {
  const lines = ["# Netscape HTTP Cookie File", "# Generated by yt-dlp-library cookie harvest", ""];
  for (const c of cookies) {
    const domain = c.domain || "";
    const includeSubdomains = domain.startsWith(".") ? "TRUE" : "FALSE";
    const cookiePath = c.path || "/";
    const secure = c.secure ? "TRUE" : "FALSE";
    const expires =
      typeof c.expires === "number" && c.expires > 0
        ? Math.floor(c.expires)
        : 0;
    const name = c.name || "";
    const value = c.value ?? "";
    lines.push(
      [domain, includeSubdomains, cookiePath, secure, String(expires), name, value].join("\t")
    );
  }
  return `${lines.join("\n")}\n`;
};

const tryPlayMedia = async (page) => {
  // Best-effort: click common play controls, then call play() on media elements.
  const playSelectors = [
    'button[aria-label*="Play" i]',
    'button[title*="Play" i]',
    '[aria-label*="Play" i]',
    ".vjs-big-play-button",
    ".ytp-large-play-button",
    "button.play",
    ".play-button",
    '[data-testid*="play" i]',
  ];

  for (const selector of playSelectors) {
    try {
      const loc = page.locator(selector).first();
      if (await loc.isVisible({ timeout: 500 })) {
        await loc.click({ timeout: 2000 });
        break;
      }
    } catch {
      /* keep trying */
    }
  }

  try {
    await page.evaluate(async () => {
      const media = Array.from(document.querySelectorAll("video, audio"));
      await Promise.all(
        media.map(async (el) => {
          try {
            el.muted = true;
            await el.play();
          } catch {
            /* autoplay may be blocked */
          }
        })
      );
    });
  } catch {
    /* ignore */
  }
};

/**
 * Open the URL in system Google Chrome, attempt playback, export cookies to a Netscape file.
 * @param {{ url: string, outputDir: string }} opts
 * @returns {Promise<string>} absolute path to the cookie file
 */
export const harvestCookiesWithChrome = async ({ url, outputDir }) => {
  if (!url || typeof url !== "string") {
    throw new Error("Cookie harvest requires a video URL.");
  }
  if (!outputDir || typeof outputDir !== "string") {
    throw new Error("Cookie harvest requires an output directory.");
  }

  const settleMs = parsePositiveInt(process.env.COOKIE_HARVEST_SETTLE_MS, DEFAULT_SETTLE_MS);
  const timeoutMs = parsePositiveInt(process.env.COOKIE_HARVEST_TIMEOUT_MS, DEFAULT_TIMEOUT_MS);
  const cookiesPath = path.join(outputDir, "harvested-cookies.txt");

  let browser;
  try {
    browser = await chromium.launch({
      channel: "chrome",
      headless: !isHeaded(),
    });
  } catch (err) {
    const msg = err?.message || String(err);
    throw new Error(
      `Failed to launch Google Chrome for cookie harvest. Ensure Chrome is installed on this machine. ${msg}`
    );
  }

  try {
    const context = await browser.newContext();
    const page = await context.newPage();
    page.setDefaultTimeout(timeoutMs);

    await page.goto(url, {
      waitUntil: "domcontentloaded",
      timeout: timeoutMs,
    });

    await tryPlayMedia(page);
    await new Promise((resolve) => setTimeout(resolve, settleMs));

    const cookies = await context.cookies();
    if (!cookies.length) {
      throw new Error(
        "Cookie harvest completed but no cookies were set. The page may require interaction or block headless Chrome."
      );
    }

    await fs.writeFile(cookiesPath, cookiesToNetscape(cookies), "utf8");
    return cookiesPath;
  } finally {
    if (browser) {
      await browser.close().catch(() => {});
    }
  }
};

/**
 * Best-effort delete of a harvested cookie file.
 */
export const cleanupCookieFile = async (cookiesPath) => {
  if (!cookiesPath) return;
  try {
    await fs.unlink(cookiesPath);
  } catch {
    /* ignore missing / already deleted */
  }
};
